"""rig status names a hook manager that overwrote a global composer (2026-09-26: a postinstall
`lefthook install` replaced ~/.config/git/hooks/pre-commit — secret scan and review gate — with a
lefthook shim). The crux: that state must read as a loud, specific drift item, not a generic diff."""

from __future__ import annotations

from pathlib import Path

from riglib.drift import DriftReport, _check_composers, hook_manager_shim

LEFTHOOK_SHIM = """#!/bin/sh

if [ "$LEFTHOOK_VERBOSE" = "1" -o "$LEFTHOOK_VERBOSE" = "true" ]; then
  set -x
fi

if [ "$LEFTHOOK" = "0" ]; then
  exit 0
fi

call_lefthook()
{
  "$LEFTHOOK_BIN" "$@"
}
"""

RIG_COMPOSER = """#!/bin/sh
# Composing global pre-commit hook (core.hooksPath = ~/.config/git/hooks).
#
# Repos with a local hook manager (lefthook/husky/raw) keep their own hooks.
exec "$(dirname "$0")/../run-global-hooks" pre-commit "$@"
"""


def test_hook_manager_shims_are_recognised():
    assert hook_manager_shim(LEFTHOOK_SHIM) == "lefthook"
    assert hook_manager_shim('#!/usr/bin/env sh\n. "$(dirname -- "$0")/_/husky.sh"\nnpx lint-staged\n') == "husky"
    assert hook_manager_shim("#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\nINSTALL_PYTHON=/usr/bin/python3\n") == "pre-commit"
    simple = '#!/bin/sh\n\nif [ "$SKIP_SIMPLE_GIT_HOOKS" = "1" ]; then\n  exit 0\nfi\nnpx lint-staged\n'
    assert hook_manager_shim(simple) == "simple-git-hooks"
    # naming the tool in a hand-written hook is not its shim
    assert hook_manager_shim("#!/bin/sh\n# replaced simple-git-hooks with this hook\nexit 0\n") is None


def test_rigs_own_composer_is_not_a_shim_even_when_it_mentions_them():
    assert hook_manager_shim(RIG_COMPOSER) is None
    assert hook_manager_shim(RIG_COMPOSER.replace("pre-commit \"$@\"", "pre-commit")) is None


def test_a_lefthook_shim_in_the_global_composer_dir_is_named_in_drift(tmp_path: Path):
    src = tmp_path / "src" / "hooks"
    src.mkdir(parents=True)
    (src / "pre-commit").write_text(RIG_COMPOSER, encoding="utf-8")
    composer = tmp_path / "global" / "hooks"
    composer.mkdir(parents=True)
    (composer / "pre-commit").write_text(LEFTHOOK_SHIM, encoding="utf-8")
    report = DriftReport()
    _check_composers(src, composer, report)
    (item,) = [i for i in report.items if i.item == "pre-commit"]
    assert item.direction == "modified"
    assert "REPLACED by a lefthook shim" in item.detail
    assert "rig apply" in item.detail


def test_an_edited_composer_keeps_the_generic_detail(tmp_path: Path):
    src = tmp_path / "src" / "hooks"
    src.mkdir(parents=True)
    (src / "pre-commit").write_text(RIG_COMPOSER, encoding="utf-8")
    composer = tmp_path / "global" / "hooks"
    composer.mkdir(parents=True)
    (composer / "pre-commit").write_text(RIG_COMPOSER + "# local edit\n", encoding="utf-8")
    report = DriftReport()
    _check_composers(src, composer, report)
    (item,) = [i for i in report.items if i.item == "pre-commit"]
    assert "composer hook differs" in item.detail
